-- 3. FIX: get_deletion_history_secure (New RPC)
CREATE OR REPLACE FUNCTION public.get_deletion_history_secure(p_viewer_id BIGINT)
RETURNS TABLE (
    id BIGINT, 
    log_id BIGINT, 
    target_user_id TEXT, 
    reason TEXT, 
    deleted_at TIMESTAMP WITH TIME ZONE,
    deleted_by_name TEXT
) LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    IF NOT public.is_staff(p_viewer_id) THEN RAISE EXCEPTION 'Access Denied'; END IF;
    RETURN QUERY SELECT h.id, h.log_id, h.target_nim, h.reason, h.deleted_at, u.full_name
    FROM public.attendance_deletion_logs h
    LEFT JOIN public.users u ON h.deleted_by_id = u.id
    ORDER BY h.deleted_at DESC;
END; $$;

